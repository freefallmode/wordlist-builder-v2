import fs from 'node:fs';
const c = JSON.parse(fs.readFileSync(new URL('./shortmem/candidates.json', import.meta.url), 'utf8'));
const P = JSON.parse(fs.readFileSync(new URL('../../data/wordlist-en.project.json', import.meta.url), 'utf8'));
const alive = new Set(P.entries.map(e => e.id));
const g = c.convert.filter(r => r.inGroup && alive.has(r.stub));
const l = c.convert.filter(r => r.full[0].linked && !r.inGroup && alive.has(r.stub));
const m = c.multi.filter(r => alive.has(r.stub));
const f = r => `${r.theme}: "${r.text}" (fam ${r.fam}, typ ${r.typ}) => ${r.full.map(x => `"${x.text}"${x.linked ? ' [already linked]' : ''}`).join(' | ')}`;
const out = ['# Held cases (library v347)', '', `## A. Stub in a synonym group (${g.length})`, ...g.map(f), '', `## B. Full term already linked to the theme (${l.length})`, ...l.map(f), '', `## C. Several possible full terms (${m.length})`, ...m.map(f)];
fs.writeFileSync(new URL('./shortmem/held.md', import.meta.url), out.join('\n') + '\n');
console.log(g.length, l.length, m.length);
